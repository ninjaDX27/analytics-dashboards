-- Credit Operations Transformation: dados 100% sintéticos. SQLite.
DROP TABLE IF EXISTS lead;
DROP TABLE IF EXISTS channel_spend;
CREATE TABLE lead (
  lead_id INTEGER PRIMARY KEY,
  source TEXT NOT NULL,
  created_at TEXT NOT NULL,
  contacted_at TEXT,
  qualified_at TEXT,
  submitted_at TEXT,
  funded_at TEXT,
  status TEXT NOT NULL CHECK(status IN ('won','lost','open'))
);
CREATE TABLE channel_spend (
  source TEXT PRIMARY KEY,
  period TEXT NOT NULL,
  media_spend_eur REAL NOT NULL CHECK(media_spend_eur >= 0)
);
